import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } })
page.on('pageerror', (e) => console.log('[pageerror]', String(e).slice(0, 150)))
await page.addInitScript(() => localStorage.setItem('drone-screen-token', 'mock-token-shot'))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.waitForTimeout(3500)
console.log('页面标题:', await page.title())
console.log('顶栏标题:', await page.locator('.top-bar__title, .topbar__title, h1').first().textContent().catch(() => '未找到'))
console.log('右下面板:', await page.locator('.panel-card__title').allTextContents())
await page.getByRole('button', { name: /模拟洪灾/ }).click()
await page.waitForTimeout(90000) // 等勘测到场/空投节点产生
const feedCount = await page.locator('.feed__item').count()
const nodeCount = await page.locator('.nodes__item').count()
const nodes = await page.locator('.nodes__item .nodes__title').allTextContents()
const feeds = (await page.locator('.feed__item').allTextContents()).slice(0, 5)
console.log('动态条数:', feedCount, '| 节点条数:', nodeCount)
console.log('节点:', JSON.stringify(nodes))
console.log('动态样本:', JSON.stringify(feeds))
await page.screenshot({ path: 'shots/20-event-panel.png' })
await browser.close()
