import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } })
await page.addInitScript(() => localStorage.setItem('drone-screen-token', 'mock-token-shot'))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.waitForTimeout(4000)
const before = await page.evaluate(() => window.__MAP.getAllOverlays('polyline').length)
await page.getByRole('button', { name: /巡航航线/ }).click()
await page.waitForTimeout(800)
const after = await page.evaluate(() => window.__MAP.getAllOverlays('polyline').length)
await page.getByRole('button', { name: /巡航航线/ }).click()
await page.waitForTimeout(800)
const off = await page.evaluate(() => window.__MAP.getAllOverlays('polyline').length)
console.log('polyline 数: 默认=' + before + ' 开启=' + after + ' 关闭=' + off)
console.log(before === 8 && after === 14 && off === 8 ? 'ROUTE TOGGLE OK' : 'ROUTE TOGGLE MISMATCH')
await browser.close()
